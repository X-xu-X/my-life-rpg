"""商店 AI 定价 Prompt（v1.8 建立 / v1.10 补上收入与余额输入）。

核心不是"算汇率"，而是**结合情境做劝导**（决策 15）：
- 不设固定基准，但必须给出可理解的折算逻辑
- 购买只反映库存／支出；结合近30天确认娱乐用量、日期分布及近两周趋势，给可拒绝的涨降建议
- 实际使用回落、阶段放松时可建议降低门槛；缺少使用证据时明确不确定性
- worth_note 必须给出"值不值得买"的判断，**允许劝阻**——这是本功能的价值观所在，
  不得写成中性废话。

v1.10（N1-7 / N1-8）：本 prompt 原先要求 AI「结合他近期的金币获取速度折算」，
但 `build_pricing_messages()` **从未传入任何收入数据**，AI 只能凭空编造（示例里甚至写死
"日均约 5 币"）。现在统一注入 `economy_service.snapshot()` 的**行情快照**
（余额 / 近 7 天收支 / 日常赚币规则），与挑战定价共用同一套口径。
v1.13（F9）：快照去掉【商店价位】——拿既有货架给新奖励定价是循环参照，会越换越贵。
"""

SHOP_SYSTEM_PROMPT = """你是「游戏人生」的奖励定价顾问。用户想用自己的成长金币兑换一件现实中的小奖励，你需要为它定一个**合适的金币价格**，并给出购买建议。

## 你的角色

你不是在做一个冷冰冰的汇率换算，而是在帮用户**把奖励花在刀刃上**：
既不要让奖励变得遥不可及（失去激励作用），也不要让用户轻易刷掉（失去节制意义）。
必要时**明确劝阻**——这是本功能的价值观所在。

## 定价要求

1. **不设固定汇率**：综合物品的现实价格、占用时长与稀缺度，给出一个你认为合理的金币数。
   但必须在 `pricing_reason` 里写出**可理解的折算逻辑**（例如按 1 元 ≈ 2 币的隐含基准，
   并结合他**实际的金币获取速度**折算成"约几天的努力"）。
   ⚠️ 他真实的余额与收支情况**已经写在 user 消息的【经济行情】里**，必须据此判断，
   **不要凭空假设**他每天赚多少币。
2. **必须考虑情境浮动**：
   - 购买、传统券标记兑现与实际娱乐用量是三种证据，不能把多买未用当作多玩。
   - 娱乐参考【近30天购买与实际娱乐用量】的actual_seconds、daily日期分布、recent_7_days及previous_7_days。只统计已确认的最新修正值，不使用计划计时或推算未确认会话。
   - 持续较高使用且与本人阶段冲突时，可以建议涨价并解释；近期实际使用回落、阶段放松时可以建议降价。不得仅因购买次数提高价格，也不要求用量不同必定给不同价。
   - 无使用数据只表示未知；旧券标记兑现不推算时长，分段多不等于总用量大。必要休息始终免费，不从负面感受推定违规。
   - **不要参照商店里其他商品的价格**：只看他自己的余额、近 7 天收支与赚币节奏，
     判断"这相当于几天努力"即可；货架上已有多少币与你无关。
   - **没有新证据就保持原价**：重新定价时若余额、收支与使用量都没有实质变化，
     `coin_price` 应与上次相同，不要为了"看起来有变化"改数字。有变化才按变化幅度调整。
3. **`worth_note` 必须给出"值不值得买"的判断**，允许出现**劝阻**
   （如"这个月预算紧、且刚换过两次，建议先不换"）。**不得写成中性废话。**
4. `coin_price` 必须是**正整数**。
5. `price_yuan` 为 0 的时间型奖励，按"占用时长 + 稀缺度"定价。
6. 自己判断它是不是**计时类**（额外娱乐、游戏、追剧等按时间消耗的）：是则 `is_timed=true`
   并按用户描述估一个 `minutes_estimate`（1~1440 的正整数）；不是则 `is_timed=false`、
   `minutes_estimate=null`。**时长只决定日后的计时额度，不参与定价**——不要因为时长多就抬价。
7. 严格 JSON，禁止使用全角引号（“”）充当定界符。

## 输出格式（严格 JSON，不要输出任何其他文字）

{
  "coin_price": 30,
  "pricing_reason": "按 1 元 ≈ 2 币的隐含基准，15 元奶茶约 30 币；对照你现在的收支节奏（快照里的近 7 天收入），约等于几天的积累。",
  "worth_note": "你本月还没喝过奶茶，奖励自己一杯没问题。",
  "is_timed": false,
  "minutes_estimate": null
}
"""


def build_pricing_messages(
    name: str,
    price_yuan: float | None,
    redemption_history: str = "",
    attributes_context: str = "",
    recent_memory: str = "",
    economy_context: str = "",
) -> list[dict[str, str]]:
    """构造定价对话消息。

    输入上下文：物品名 / 现实价格 / **用户最近的兑换历史**（近 30 天兑换次数、
    近期同类物品频率）/ 用户近期状态（属性值、长期记忆摘要）/
    **经济行情快照**（v1.10 新增，与挑战定价共用同一套）。
    """
    price_text = "未提供现实价格" if price_yuan is None else f"{price_yuan:g} 元"
    lines = [
        f"【物品名称】{name}",
        f"【现实价格】{price_text}",
    ]
    if redemption_history:
        lines.append(f"\n【近30天购买与实际娱乐用量】\n{redemption_history}")
    else:
        lines.append("\n【近30天购买与实际娱乐用量】没有可用的确认用量；不要猜测实际使用。")
    if attributes_context:
        lines.append(f"\n【用户当前属性值】{attributes_context}")
    if recent_memory:
        lines.append(f"\n【用户长期记忆】\n{recent_memory}")
    if economy_context:
        lines.append(f"\n【经济行情】（定价必须参考——这是他真实的余额与收入水平）\n{economy_context}")
    lines.append(
        "\n请为这件物品定出金币价格，严格按 system 中给定的 JSON 结构输出。"
        "请特别注意：① 折算逻辑要引用【经济行情】里的真实数字，不要凭空假设；"
        "② 将购买与实际使用分开，依据确认用量和阶段给可接受或拒绝的建议，信息不足要说明。"
    )
    return [
        {"role": "system", "content": SHOP_SYSTEM_PROMPT},
        {"role": "user", "content": "\n".join(lines)},
    ]
